DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS vector;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'pgvector суулгаагүй тул RAG-гүй ажиллана';
END $$;

ALTER TABLE contracts
    ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS owner_email TEXT,
    ADD COLUMN IF NOT EXISTS owner_phone TEXT,
    ADD COLUMN IF NOT EXISTS tenant_email TEXT,
    ADD COLUMN IF NOT EXISTS tenant_phone TEXT,
    ADD COLUMN IF NOT EXISTS area_sqm NUMERIC(10, 2),
    ADD COLUMN IF NOT EXISTS rooms SMALLINT,
    ADD COLUMN IF NOT EXISTS payment_day SMALLINT DEFAULT 1,
    ADD COLUMN IF NOT EXISTS owner_signed BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS tenant_signed BOOLEAN DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS request_data JSONB;

CREATE INDEX IF NOT EXISTS idx_contracts_user ON contracts(user_id);
